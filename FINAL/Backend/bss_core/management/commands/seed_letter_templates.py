class Command(BaseCommand):
    help = "Seed the all-India default Appointment / Experience letter templates."

    def handle(self, *args, **options):
        created = 0
        for name, kind, html in (
            ("All-India Appointment Letter", "APPOINTMENT", APPOINTMENT_HTML),
            ("All-India Experience / Releasing Letter", "EXPERIENCE", EXPERIENCE_HTML),
        ):
            _, made = LetterTemplate.objects.get_or_create(
                state="", letter_type=kind, name=name,
                defaults={"html": html, "is_active": True})
            created += int(made)
        self.stdout.write(self.style.SUCCESS(
            f"Letter templates ready ({created} created, "
            f"{LetterTemplate.objects.count()} total)."))
