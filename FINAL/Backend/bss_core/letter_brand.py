"""Letter page box + optional BSS branding.

Every letter needs a safe A4 page box. The built-in templates hardcode
``.page { width:794px }`` — the full A4 width at 96dpi — while WeasyPrint
applies a non-zero default ``@page`` margin, so the fixed-width block overflowed
the page box and was clipped down the right-hand edge. ``PRINT_CSS`` pins an
explicit page box and drops the pixel width so the layout is page-driven.

BSS branding (logo + wordmark header) is applied only where ``wants_logo()``
allows it. Appointment letters and the experience / releasing letter are issued
by the contractor / employer, so they must not carry a BSS logo or wordmark:
appointment letters omit branding entirely, and the experience letter is the
statutory Form XV service certificate under Rule 77 of the Contract Labour
(Regulation & Abolition) Rules, which likewise must stay unbranded. Pass
``with_logo=False`` (the default for ``EXPERIENCE``/``APPOINTMENT``) to keep the
page box fix while leaving the document unbranded.

``ensure_letter_html()`` applies both concerns, and ``ensure_logo_url()``
supplies the hosted default only where branding is wanted. Both are idempotent,
so they are safe at render time, at API-serialisation time and as a backfill.
"""

from __future__ import annotations

import re

DEFAULT_LOGO_URL = "https://login.bharatshramsetu.com/bss-brand/bharatshramsetu-logo.png"

# Letter types that must never receive BSS branding (statutory government
# format). The experience / releasing letter is the statutory Form XV service
# certificate, which must stay unbranded. Appointment letters DO carry the BSS
# brand row + logo (the admin template editor expects it).
UNBRANDED_LETTER_TYPES = {"EXPERIENCE"}

# Optional per-state opt-out of BSS branding. Empty: no state is suppressed —
# every state's appointment letter carries the BSS brand row + logo.
LOGO_SUPPRESSED_STATES: set[str] = set()

# Bump when the CSS changes so previously-injected stylesheets get replaced.
_CSS_MARKER = "bss-letter-css-v5"
_INJECTED_RE = re.compile(r"<style[^>]*>\s*bss-letter-css[^<]*</style>", re.I)

# Layout safety — applied to every letter, branded or not.
PRINT_CSS = """
  @page { size: A4; margin: 12mm 14mm; }
  .page { width:auto; max-width:100%; margin:0; padding:0; }
  table, img { max-width:100%; }
  .sign .id, .sign-col .id { font-size:8.5pt; color:#6b7280; font-family:monospace; margin-top:2px; }
  /* On-screen / preview only: emulate the @page margins so the letter is not
     flush to the frame edges. WeasyPrint (print media) ignores this. */
  @media screen { .page { padding: 14mm 14mm; box-sizing: border-box; } }
"""

# Form XV signature block must carry the worker's and contractor's BSS ID
# alongside the name. (anchor, replacement, token that marks it as done)
_SIGN_ID_PATCHES = (
    ("<div>Signature of Workman</div>",
     '<div>Signature of Workman</div><div class="id">BSS ID: {{workerBssId}}</div>',
     "{{workerBssId}}"),
    ("<div>Signature of Contractor / Authorized Signatory</div>",
     '<div>Signature of Contractor / Authorized Signatory</div>'
     '<div class="id">BSS ID: {{contractorBssId}}</div>',
     "{{contractorBssId}}"),
)

# The seeded Form XV footer credited BSS. Form XV is a statutory government
# certificate, so the footer now cites only the rule it is issued under.
_LEGACY_FOOTERS = (
    "Generated under Central Contract Labour (Regulation &amp; Abolition) Rules"
    " &middot; Bharat Shram Setu",
    "Generated under Central Contract Labour (Regulation &amp; Abolition) Rules"
    " &middot; Bharat Shram Setu",
    "Generated under Central Contract Labour (Regulation &amp; Abolition) Rules"
    " · Bharat Shram Setu",
    "Generated under Central Contract Labour (Regulation &amp; Abolition) Rules, 1971"
    " · Bharat Shram Setu",
)
_STATUTORY_FOOTER = ("Form XV Service Certificate under Rule 77, Contract Labour "
                     "(Regulation &amp; Abolition) Rules, 1971")

# The seeded appointment-letter footer credited BSS. Appointment letters must
# carry no BSS branding, so this credit is stripped entirely.
_BSS_FOOTER_RE = re.compile(
    r'<div class="foot">[^<]*Generated by Bharat Shram Setu[^<]*</div>', re.I)

# BSS brand row — appointment letters only. Table layout because WeasyPrint
# ignores flexbox; explicit logo height so a portrait PNG cannot blow out the row.
BRAND_CSS = """
  .bss-letter-brand { display:table; width:100%; border-bottom:2.5px solid #073B67;
                      padding:0 0 6px; margin:2px 0 10px; }
  .bss-letter-brand .brand-left { display:table-cell; vertical-align:middle; width:54px; }
  .bss-letter-brand .brand-logo { height:42px; width:auto; max-width:52px;
                                  display:block; vertical-align:middle; }
  .bss-letter-brand .brand-title { display:table-cell; vertical-align:middle;
                                   padding-left:10px; }
  .bss-letter-brand .brand-title strong { color:#073B67; font-size:16px; letter-spacing:.3px;
                                          display:block; line-height:1.15; }
  .bss-letter-brand .brand-title span { display:block; font-size:8.5px; color:#6b7280;
                                        letter-spacing:1.2px; text-transform:uppercase; margin-top:1px; }
"""

BRAND_BLOCK = (
    '<div class="brand bss-letter-brand">'
    '<div class="brand-left">'
    '<img src="{{logoUrl}}" alt="Bharat Shram Setu" class="brand-logo"/>'
    "</div>"
    '<div class="brand-title"><strong>Bharat Shram Setu</strong>'
    "<span>One Worker · One Identity · One Future</span></div>"
    "</div>"
)

_IMG_RE = re.compile(r"<img\b[^>]*>", re.I)
_CLASS_RE = re.compile(r'class\s*=\s*"([^"]*)"', re.I)
_HEAD_RE = re.compile(r"</head\s*>|<body[^>]*>", re.I)
_PAGE_RE = re.compile(r'<div\s+class\s*=\s*"page"[^>]*>', re.I)
_FIRST_BLOCK_RE = re.compile(r"<(?:div|table|h1|h3|p)\b", re.I)
# Matches the exact block we inject, so it can be removed again on request.
_BRAND_BLOCK_RE = re.compile(
    r'<div class="(?:brand bss-letter-brand|bss-letter-brand brand)">.*?</div>\s*</div>',
    re.I | re.S)


def strip_injected_css(html_text: str) -> str:
    """Return *html_text* without any stylesheet we previously injected.

    Used when snapshotting templates to code: the injected block is derived from
    ``PRINT_CSS`` / ``BRAND_CSS``, so storing it would make the snapshot stale
    as soon as those change. The restore re-applies it.
    """
    if not html_text:
        return html_text
    return _INJECTED_RE.sub("", html_text)


def wants_logo(letter_type: str, with_logo: bool | None = None, state: str | None = None) -> bool:
    """Whether this letter type may carry BSS branding (and a BSS logo)."""
    if with_logo is not None:
        return bool(with_logo)
    if state is not None and str(state).strip() in LOGO_SUPPRESSED_STATES:
        return False
    return (letter_type or "").strip().upper() not in UNBRANDED_LETTER_TYPES


def ensure_logo_url(value, letter_type: str = "APPOINTMENT",
                    with_logo: bool | None = None, state: str | None = None) -> str:
    """Return the template's logo URL, or the hosted BSS default.

    Always blank for unbranded types (statutory Form XV) or any state listed in
    ``LOGO_SUPPRESSED_STATES`` (currently none), discarding whatever was passed in.
    """
    text = (value or "").strip()
    if not wants_logo(letter_type, with_logo, state):
        return ""
    return text or DEFAULT_LOGO_URL


def _is_logo_img(tag: str) -> bool:
    return "logourl" in tag.lower() or "bharatshramsetu-logo" in tag.lower()


def _size_logo_img(tag: str) -> str:
    """Ensure the logo <img> carries the brand-logo class (print-safe sizing)."""
    found = _CLASS_RE.search(tag)
    if found is None:
        return tag.replace("<img", '<img class="brand-logo"', 1)
    classes = found.group(1).split()
    if "brand-logo" in classes:
        return tag
    return tag.replace(found.group(0), f'class="{" ".join(classes + ["brand-logo"])}"', 1)


def _mark_brand_row(out: str) -> str:
    """Add the marker class to an existing brand row so our CSS applies."""
    def repl(match: re.Match) -> str:
        tag = match.group(0)
        if not _CLASS_RE.search(tag):
            return tag.replace('class="', 'class="bss-letter-brand ', 1)
        if "bss-letter-brand" in tag:
            return tag
        return _CLASS_RE.sub(
            lambda m: f'class="bss-letter-brand {m.group(1)}"', tag, count=1)

    return re.sub(r'<div\s+class\s*=\s*"brand"[^>]*>', repl, out, count=1, flags=re.I)


def _rebuild_brand_row(out: str) -> str:
    """Replace an existing brand row with the canonical structure.

    Older templates wrap the logo image and wordmark in bare elements (no
    ``.brand-left`` / ``.brand-title`` table cells), which misaligns the logo and
    crowds it against the page edge. Rebuilding to the canonical block makes the
    logo/wordmark alignment and spacing consistent everywhere.
    """
    match = _BRAND_BLOCK_RE.search(out)
    if match is None:
        return out
    return out[:match.start()] + BRAND_BLOCK + out[match.end():]


def _ensure_sign_ids(out: str) -> str:
    """Add the BSS ID line under each name in a Form XV signature block.

    Idempotent: a template that already carries the token is left alone, and a
    template without the expected caption is simply skipped.
    """
    for anchor, replacement, token in _SIGN_ID_PATCHES:
        if token in out or anchor not in out:
            continue
        out = out.replace(anchor, replacement, 1)
    return out


def _neutralise_footer(out: str) -> str:
    """Replace a BSS-credited Form XV footer with the statutory citation."""
    if _STATUTORY_FOOTER in out:
        return out
    for legacy in _LEGACY_FOOTERS:
        if legacy in out:
            return out.replace(legacy, _STATUTORY_FOOTER, 1)
    return out


def ensure_letter_html(html_text: str, letter_type: str = "APPOINTMENT",
                       with_logo: bool | None = None, state: str | None = None) -> str:
    """Return template HTML with a safe A4 page box, plus BSS branding when allowed.

    ``with_logo`` defaults to False for statutory types such as ``EXPERIENCE``
    (Form XV) and appointment letters, so those never gain a BSS logo or
    wordmark. Idempotent: re-running on already-upgraded HTML changes nothing.
    """
    if not html_text or not html_text.strip():
        return html_text

    out = html_text
    brand = wants_logo(letter_type, with_logo, state)

    if brand:
        # 1. Logo <img> must be size-constrained, or a portrait logo blows up the header.
        out = _IMG_RE.sub(lambda m: _size_logo_img(m.group(0)) if _is_logo_img(m.group(0))
                          else m.group(0), out)

        # 2. Templates with no logo block at all get one injected.
        if "{{logoUrl}}" not in out and DEFAULT_LOGO_URL not in out:
            page = _PAGE_RE.search(out)
            if page is not None:
                out = out[:page.end()] + "\n" + BRAND_BLOCK + out[page.end():]
            else:
                first = _FIRST_BLOCK_RE.search(out)
                if first is not None:
                    out = out[:first.start()] + BRAND_BLOCK + "\n" + out[first.start():]

        # 3. Existing brand rows need the marker class, then get normalised to the
        #    canonical block so the logo/wordmark align (legacy rows used bare divs).
        out = _mark_brand_row(out)
        out = _rebuild_brand_row(out)
    else:
        # Unbranded types: drop any BSS brand row we previously injected, and make
        # sure the Form XV signature block identifies both signatories by BSS ID.
        out = _BRAND_BLOCK_RE.sub("", out)
        out = _ensure_sign_ids(out)
        out = _neutralise_footer(out)
        out = _BSS_FOOTER_RE.sub("", out)

    # 4. Replace any previously-injected stylesheet with the current one.
    out = _INJECTED_RE.sub("", out)
    css = PRINT_CSS + (BRAND_CSS if brand else "")
    style = f"<style>{_CSS_MARKER}\n{css}</style>"
    head = _HEAD_RE.search(out)
    if head is not None:
        out = out[:head.start()] + style + out[head.start():]
    else:
        out = style + out

    return out


def _esc(value: str) -> str:
    return (value or "").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def _replace_brand_name(out: str, name: str) -> str:
    """Swap the brand wordmark text inside the brand row (if present)."""
    match = _BRAND_BLOCK_RE.search(out)
    if match is None:
        return out
    block = re.sub(r"(<strong[^>]*>).*?(</strong>)",
                   lambda m: m.group(1) + _esc(name) + m.group(2),
                   match.group(0), count=1, flags=re.I | re.S)
    return out[:match.start()] + block + out[match.end():]


def _replace_footer(out: str, text: str) -> str:
    """Replace an existing footer, or append one inside the page box."""
    if re.search(r'<div\s+class\s*=\s*"foot"', out, re.I):
        return re.sub(r'(<div\s+class\s*=\s*"foot"[^>]*>).*?(</div>)',
                      lambda m: m.group(1) + _esc(text) + m.group(2),
                      out, count=1, flags=re.I | re.S)
    footer = ('<div style="margin-top:14px;border-top:1px solid #e5e7eb;padding-top:5px;'
              'font-size:9px;color:#6b7280;text-align:center">' + _esc(text) + "</div>")
    return re.sub(r"</div>\s*</body>", footer + r"\g<0>", out, count=1, flags=re.I)


def apply_letter_customizations(html_text: str, adoption) -> str:
    """Apply an employer's appointment-letter adoption overrides.

    Text/heading colours, the brand wordmark and the footer are applied here.
    The logo is applied through the ``logoUrl`` token at render time. Idempotent:
    the colour override is marked and replaced, never stacked.
    """
    if not html_text or adoption is None:
        return html_text
    out = re.sub(r"<style>\s*/\* employer-letter-adoption \*/.*?</style>", "", html_text,
                 flags=re.I | re.S)
    css = ""
    text_color = (getattr(adoption, "text_color", "") or "").strip()
    heading_color = (getattr(adoption, "heading_color", "") or "").strip()
    if text_color:
        css += ("\n  body, .page, .page p, .page td, .page span, .page div "
                f"{{ color:{text_color}; }}")
    if heading_color:
        css += (f"\n  h1, h3, .brand strong, .brand-title strong, .kv td:first-child "
                f"{{ color:{heading_color}; }}")
    if css:
        style = f"<style>/* employer-letter-adoption */{css}</style>"
        head = _HEAD_RE.search(out)
        out = out[:head.start()] + style + out[head.start():] if head is not None else style + out
    brand = (getattr(adoption, "brand_name", "") or "").strip()
    if brand:
        out = _replace_brand_name(out, brand)
    footer = (getattr(adoption, "footer_text", "") or "").strip()
    if footer:
        out = _replace_footer(out, footer)
    # Employer-authored regions (header / clauses / footer) override the base.
    header_html = (getattr(adoption, "header_html", "") or "").strip()
    if header_html:
        out = _replace_header_region(out, header_html)
    clauses_html = (getattr(adoption, "clauses_html", "") or "").strip()
    if clauses_html:
        out = _insert_clauses(out, clauses_html)
    footer_html = (getattr(adoption, "footer_html", "") or "").strip()
    if footer_html:
        out = _set_footer_region(out, footer_html)
    return out


def _replace_header_region(out: str, block: str) -> str:
    """Swap the brand/header row for employer-authored HTML (or inject one)."""
    match = _BRAND_BLOCK_RE.search(out)
    if match is not None:
        return out[:match.start()] + block + out[match.end():]
    page = _PAGE_RE.search(out)
    if page is not None:
        return out[:page.end()] + "\n" + block + out[page.end():]
    head = _HEAD_RE.search(out)
    return (out[:head.end()] + block + out[head.end():]) if head is not None else block + out


def _set_footer_region(out: str, block: str) -> str:
    """Replace an existing footer with employer HTML, or append one."""
    if re.search(r'<div\s+class\s*=\s*"foot"', out, re.I):
        return re.sub(r'<div\s+class\s*=\s*"foot"[^>]*>.*?</div>', lambda _m: block,
                      out, count=1, flags=re.I | re.S)
    return re.sub(r"</div>\s*</body>", block + r"\g<0>", out, count=1, flags=re.I)


def _insert_clauses(out: str, block: str) -> str:
    """Insert employer clauses before the signature block (else before the footer)."""
    match = re.search(r'<div\s+class\s*=\s*"sign"', out, re.I)
    if match is not None:
        return out[:match.start()] + block + "\n" + out[match.start():]
    if re.search(r'<div\s+class\s*=\s*"foot"', out, re.I):
        return re.sub(r'(<div\s+class\s*=\s*"foot"[^>]*>)', block + r"\1", out, count=1, flags=re.I)
    return re.sub(r"</div>\s*</body>", block + r"\g<0>", out, count=1, flags=re.I)
